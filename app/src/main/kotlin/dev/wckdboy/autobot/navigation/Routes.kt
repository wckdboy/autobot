package dev.wckdboy.autobot.navigation

import androidx.navigation3.runtime.NavKey
import kotlinx.serialization.Serializable

/** Bottom-bar destinations (RUN · MODELS · REMOTE · SETTINGS). Selecting one resets the stack. */
sealed interface TopLevel : NavKey

@Serializable
data object Run : TopLevel

@Serializable
data object Models : TopLevel

@Serializable
data object Remote : TopLevel

@Serializable
data object Settings : TopLevel

/** All sessions. */
@Serializable
data object ChatList : NavKey

@Serializable
data class Chat(val conversationId: String) : NavKey

/**
 * @param handoffId gallery item to load ([asInit] = as img2img input, else reuse its params).
 * @param modelId installed on-device model to select (tapped on the Models screen).
 * @param prompt prompt to fill in (system entry points; never generated by itself).
 * @param action what to do with [handoffId], a `ViewerAction` name (img2img, inpaint, vary,
 *   reuse, same seed); null = [asInit]'s img2img or reuse.
 */
@Serializable
data class Imagine(
    val handoffId: String? = null,
    val asInit: Boolean = false,
    val modelId: String? = null,
    val prompt: String? = null,
    val action: String? = null,
) : NavKey

/** The Creative Studio; [room] is a `StudioRoom` name (image, audio, video, workflows, library). */
@Serializable
data class Studio(val room: String? = null) : NavKey

/** The gallery; [openId] opens the full-screen viewer on it, swiping through [scope] (a chat's batch) when given. */
@Serializable
data class Gallery(val openId: String? = null, val scope: List<String> = emptyList()) : NavKey

@Serializable
data object Providers : NavKey

/** The Autobot Agent on a paired Invincible node ([providerId]: its "My node" provider). */
@Serializable
data class NodeAgent(val providerId: String) : NavKey

@Serializable
data object McpServers : NavKey

@Serializable
data object PrivacyCenter : NavKey

@Serializable
data object ImageBackends : NavKey

@Serializable
data object Accounts : NavKey

/** Compute; [report]: open its diagnostics report at once (About → Copy diagnostics). */
@Serializable
data class Compute(val report: Boolean = false) : NavKey

/** Version, release notes, links, licenses and the signing key. */
@Serializable
data object About : NavKey

@Serializable
data object Memory : NavKey

/** The spend and quota board: tokens, cost and subscription windows, counted on this phone. */
@Serializable
data object Usage : NavKey

@Serializable
data object Vault : NavKey

/** Scheduled on-device recipes (Settings › Recipes). */
@Serializable
data object Recipes : NavKey
