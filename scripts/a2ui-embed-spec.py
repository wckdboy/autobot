#!/usr/bin/env python3
"""Embeds the vendored A2UI v1.0 schemas and basic catalog into commonMain.

Source: shared/src/jvmTest/resources/a2ui/v1_0 (copied from github.com/google/A2UI, see NOTICE).
Output: shared/src/commonMain/kotlin/dev/wckdboy/autobot/shared/a2ui/A2uiSpecJson.kt
Run from the repository root after updating the vendored files.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "shared/src/jvmTest/resources/a2ui/v1_0")
OUT = os.path.join(ROOT, "shared/src/commonMain/kotlin/dev/wckdboy/autobot/shared/a2ui/A2uiSpecJson.kt")

FILES = [
    ("commonTypes", "json/common_types.json"),
    ("agentToRenderer", "json/agent_to_renderer.json"),
    ("catalogDefinition", "json/catalog_definition.json"),
    ("basicCatalog", "catalogs/basic/catalog.json"),
]


def kotlin_literal(text, chunk=4000):
    parts = []
    for i in range(0, len(text), chunk):
        piece = text[i:i + chunk]
        piece = piece.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("\n", "\\n")
        parts.append('        "' + piece + '",')
    return "\n".join(parts)


def main():
    out = [
        "// Generated by scripts/a2ui-embed-spec.py from shared/src/jvmTest/resources/a2ui/v1_0. Do not edit.",
        "// A2UI v1.0 (github.com/google/A2UI, commit d71cc92), Copyright Google LLC, Apache License 2.0.",
        "package dev.wckdboy.autobot.shared.a2ui",
        "",
        "/** The A2UI v1.0 schemas and basic catalog, minified, as shipped in the app. */",
        "internal object A2uiSpecJson {",
    ]
    for name, rel in FILES:
        with open(os.path.join(SRC, rel), encoding="utf-8") as f:
            data = json.load(f)
        text = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
        out.append(f"    /** {rel} */")
        out.append(f"    val {name}: String by lazy {{")
        out.append("        listOf(")
        out.append(kotlin_literal(text))
        out.append('        ).joinToString("")')
        out.append("    }")
        out.append("")
    out[-1] = "}"
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    sys.exit(main())
