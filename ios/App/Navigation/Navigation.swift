import Observation
import SwiftUI
import UIKit

/// Bottom-bar destinations (RUN · MODELS · REMOTE · SETTINGS). Selecting one resets the stack.
enum Tab: String, CaseIterable, Hashable {
    case run, models, remote, settings

    var label: String { rawValue }
}

/// Detail screens pushed on top of a tab root (they hide the bottom bar).
enum Destination: Hashable {
    /// All sessions.
    case chatList
    case chat(conversationId: String)
    /// [handoffId]: gallery item to load, for [intent] (reuse its settings, same seed, img2img, vary, inpaint).
    /// [modelId]: installed on-device model to select (tapped on the Models screen).
    /// [prompt]: prompt to fill in (system entry points; never generated by itself).
    case imagine(handoffId: String? = nil, intent: ImageHandoff = .reuse, modelId: String? = nil, prompt: String? = nil)
    case gallery(openId: String? = nil)
    case providers
    case mcpServers
    case privacyCenter
    case imageBackends
    case accounts
    case compute
    case licenses
    case about
    case memory
    case vault
    /// The spend and quota board.
    case usage
    /// Scheduled on-device recipes.
    case recipes
    /// The Autobot Agent on a paired node ([providerId]: its "My node" provider); [open] is a sheet to
    /// open on arrival (the Run screen's "While you were away").
    case nodeAgent(providerId: String, open: NodeAgentSheet? = nil)
}

/// The Creative Studio's rooms (its own bar while the Studio is open).
enum StudioRoom: String, CaseIterable, Hashable {
    case image, audio, video, workflows, library

    var label: String { rawValue }

    /// Darkroom for image and video, paper for the library, the app's theme elsewhere.
    var surface: StudioSurface {
        switch self {
        case .image, .video: .darkroom
        case .library: .paper
        case .audio, .workflows: .app
        }
    }
}

enum StudioSurface { case darkroom, paper, app }

/// One back stack whose root is a tab (Android's Navigation 3 `NavDisplay`).
@MainActor
@Observable
final class Navigator {
    var tab: Tab = .run
    var path: [Destination] = []
    /// The Studio is open on this room (it replaces the app until [leaveStudio]); the app's stack waits underneath.
    var studio: StudioRoom?
    /// A workflow handed over to import (share sheet), shown by the Workflows room.
    var pendingWorkflow: String?
    /// An `invincible://pair?…` code from a link, for the Providers screen's pairing sheet.
    var pendingPairing: String?

    init() {
        #if DEBUG
        // UI work: `-AutobotOpen <screen>` starts on that screen.
        let args = ProcessInfo.processInfo.arguments
        if let i = args.firstIndex(of: "-AutobotOpen"), i + 1 < args.count {
            switch args[i + 1] {
            case "imagine": path = [.imagine()]
            case "gallery": path = [.gallery()]
            case "viewer": path = [.gallery(openId: GalleryScreen.newest)]
            case "backends": path = [.imageBackends]
            case "models": tab = .models
            case "compute": tab = .models; path = [.compute]
            case "accounts": tab = .models; path = [.accounts]
            case "remote": tab = .remote
            case "settings": tab = .settings
            case "sessions": path = [.chatList]
            case "privacy": tab = .settings; path = [.privacyCenter]
            case "providers": tab = .remote; path = [.providers]
            case "about": tab = .settings; path = [.about]
            case "mcp": tab = .settings; path = [.mcpServers]
            case "licenses": tab = .settings; path = [.licenses]
            case "memory": tab = .settings; path = [.memory]
            case "vault": tab = .settings; path = [.vault]
            case "usage": tab = .settings; path = [.usage]
            case "recipes": tab = .settings; path = [.recipes]
            case "studio": studio = .image
            default:
                if args[i + 1].hasPrefix("studio-") { studio = StudioRoom(rawValue: String(args[i + 1].dropFirst(7))) }
            }
        }
        #endif
    }

    /// Pushes without the slide: the new screen inks in instead ([View.inkArrive]). Going back
    /// (button or edge swipe) keeps the native, interactive pop.
    func push(_ destination: Destination) {
        guard path.last != destination else { return }
        var transaction = Transaction()
        transaction.disablesAnimations = true
        withTransaction(transaction) { path.append(destination) }
    }

    /// Opens the Studio (Home, Imagine, the agent's results); the app stays where it was.
    func enterStudio(_ room: StudioRoom = .image) {
        withAnimation(.inkSlide) { studio = room }
    }

    func leaveStudio() {
        withAnimation(.inkSlide) { studio = nil }
    }

    func back() {
        if !path.isEmpty { path.removeLast() }
    }

    func switchTo(_ tab: Tab) {
        path = []
        self.tab = tab
    }

    /// Replaces the whole stack (welcome screen shortcuts).
    func reset(_ tab: Tab, _ destinations: [Destination] = []) {
        self.tab = tab
        path = destinations
    }
}

/**
 Navigation host: the tab root with pushed details on top. The image studio is printed on paper
 (light) as in the mockups. Screens draw their own riso top bars, so the system navigation bar is
 hidden (the edge-swipe back gesture stays enabled). Pushed screens and tab roots ink in
 (motion spec v2 §3).
 */
struct AutobotNavHost: View {
    @Environment(Navigator.self) private var nav
    @Environment(\.scheme) private var c

    var body: some View {
        // The app stays underneath (its stack and screens keep their state) while the Studio is open.
        let inStudio = nav.studio != nil
        ZStack {
            app
                // Hidden, not removed: its living cards and grounds must not keep ticking.
                .environment(\.inkOffscreen, inStudio)
                .opacity(inStudio ? 0 : 1)
                .allowsHitTesting(!inStudio)
                .accessibilityHidden(inStudio)
            if inStudio {
                StudioScreen()
                    .transition(.opacity)
            }
        }
    }

    private var app: some View {
        @Bindable var nav = nav
        return VStack(spacing: 0) {
            NavigationStack(path: $nav.path) {
                root
                    .inkArrive()
                    .id(nav.tab)
                    .toolbar(.hidden, for: .navigationBar)
                    .navigationDestination(for: Destination.self) { destination in
                        screen(destination)
                            .inkArrive()
                            .toolbar(.hidden, for: .navigationBar)
                            .background(c.background.ignoresSafeArea())
                    }
            }
            if nav.path.isEmpty {
                AutobotNavBar(items: Tab.allCases.map { NavItem(key: $0, label: $0.label) }, selected: nav.tab) { selected in
                    if selected != nav.tab { nav.switchTo(selected) }
                }
            }
        }
        .background(c.background.ignoresSafeArea())
    }

    @ViewBuilder private var root: some View {
        switch nav.tab {
        case .run: RunScreen()
        case .models: ModelsScreen()
        case .remote: RemoteScreen()
        case .settings: SettingsScreen()
        }
    }

    @ViewBuilder private func screen(_ destination: Destination) -> some View {
        switch destination {
        case .chatList: ChatListScreen()
        case .chat(let id): ChatScreen(conversationId: id).id(id)
        case .imagine(let handoff, let intent, let modelId, let prompt): ImagineScreen(handoffId: handoff, intent: intent, modelId: modelId, prompt: prompt)
        case .gallery(let openId): GalleryScreen(openId: openId)
        case .providers: ProvidersScreen()
        case .mcpServers: McpServersScreen()
        case .privacyCenter: PrivacyCenterScreen()
        case .imageBackends: BackendsScreen()
        case .accounts: AccountsScreen()
        case .compute: ComputeScreen()
        case .licenses: LicensesScreen()
        case .about: AboutScreen()
        case .memory: MemoryScreen()
        case .vault: VaultScreen()
        case .usage: UsageScreen()
        case .recipes: RecipesScreen()
        case .nodeAgent(let providerId, let open): NodeAgentScreen(providerId: providerId, open: open).id(providerId)
        }
    }
}

/// Keeps the interactive pop gesture working while the navigation bar is hidden.
extension UINavigationController: @retroactive UIGestureRecognizerDelegate {
    override open func viewDidLoad() {
        super.viewDidLoad()
        interactivePopGestureRecognizer?.delegate = self
    }

    public func gestureRecognizerShouldBegin(_ gestureRecognizer: UIGestureRecognizer) -> Bool {
        viewControllers.count > 1
    }
}
