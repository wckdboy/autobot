import Observation
import SwiftUI
import UIKit

/// The app's sections: a tab bar on iPhone, a sidebar on iPad and the Mac. Each keeps its own stack.
enum Tab: String, CaseIterable, Hashable {
    case run, models, remote, harness, settings

    var label: String { rawValue }

    var title: String {
        switch self {
        case .run: "Run"
        case .models: "Models"
        case .remote: "Remote"
        case .harness: "Harness"
        case .settings: "Settings"
        }
    }

    var symbol: String {
        switch self {
        case .run: "house"
        case .models: "cpu"
        case .remote: "server.rack"
        case .harness: "terminal"
        case .settings: "gearshape"
        }
    }
}

/// Detail screens pushed on top of a tab root.
enum Destination: Hashable {
    /// All sessions.
    case chatList
    case chat(conversationId: String)
    /// [handoffId]: gallery item to load, for [intent] (reuse its settings, same seed, img2img, vary, inpaint).
    /// [modelId]: installed on-device model to select (tapped on the Models screen).
    /// [prompt]: prompt to fill in (system entry points; never generated by itself).
    case imagine(handoffId: String? = nil, intent: ImageHandoff = .reuse, modelId: String? = nil, prompt: String? = nil)
    case gallery(openId: String? = nil)
    case providers
    case mcpServers
    case privacyCenter
    case imageBackends
    case accounts
    case compute
    case licenses
    case about
    case memory
    case vault
    /// The spend and quota board.
    case usage
    /// Scheduled on-device recipes.
    case recipes
    /// The Autobot Agent on a paired node ([providerId]: its "My node" provider); [open] is a sheet to
    /// open on arrival (the Run screen's "While you were away").
    /// [bot]: the bot the conversation belongs to (bots mode); with no [session], a new chat with it.
    case nodeAgent(providerId: String, open: NodeAgentSheet? = nil, session: String? = nil, bot: String? = nil)
    /// One bot on a paired node (bots mode): its state, channels, sessions and approvals.
    case nodeBot(providerId: String, name: String)
    /// The A2UI renderer's debug preview (contact form, component gallery); `-AutobotOpen a2ui` only.
    case a2uiPreview
}

/// The Creative Studio's rooms (its own tabs while the Studio is open).
enum StudioRoom: String, CaseIterable, Hashable {
    case image, audio, video, workflows, library

    var label: String { rawValue }
}

/// A stack of screens per tab; [path] is the selected tab's.
@MainActor
@Observable
final class Navigator {
    var tab: Tab = .run
    var paths: [Tab: [Destination]] = [:]
    /// The selected tab's stack.
    var path: [Destination] {
        get { paths[tab] ?? [] }
        set { paths[tab] = newValue }
    }
    /// The Studio is open on this room (it replaces the app until [leaveStudio]); the app's stack waits underneath.
    var studio: StudioRoom?
    /// A workflow handed over to import (share sheet), shown by the Workflows room.
    var pendingWorkflow: String?
    /// An `invincible://pair?…` code from a link, for the Providers screen's pairing sheet.
    var pendingPairing: String?
    /// The welcome screen's "Add an API key": the Providers screen opens its preset picker.
    var pendingAddProvider = false

    init() {
        #if DEBUG
        // UI work: `-AutobotOpen <screen>` starts on that screen.
        let args = ProcessInfo.processInfo.arguments
        if let i = args.firstIndex(of: "-AutobotOpen"), i + 1 < args.count {
            switch args[i + 1] {
            case "imagine": path = [.imagine()]
            case "gallery": path = [.gallery()]
            case "viewer": path = [.gallery(openId: GalleryScreen.newest)]
            case "backends": path = [.imageBackends]
            case "models": tab = .models
            case "compute": tab = .models; path = [.compute]
            case "accounts": tab = .models; path = [.accounts]
            case "run": tab = .run
            case "remote": tab = .remote
            case "node": tab = .remote; path = [.nodeAgent(providerId: "demo-node")]
            // The demo node's ops bot (Bot detail).
            case "bot": tab = .remote; path = [.nodeBot(providerId: BotsDemo.nodeId, name: "ops")]
            case "harness": tab = .harness

            case "settings": tab = .settings
            case "sessions": path = [.chatList]
            case "privacy": tab = .settings; path = [.privacyCenter]
            case "providers": tab = .remote; path = [.providers]
            case "about": tab = .settings; path = [.about]
            case "mcp": tab = .settings; path = [.mcpServers]
            case "licenses": tab = .settings; path = [.licenses]
            case "memory": tab = .settings; path = [.memory]
            case "vault": tab = .settings; path = [.vault]
            case "usage": tab = .settings; path = [.usage]
            case "recipes": tab = .settings; path = [.recipes]
            case "studio": studio = .image
            case "a2ui": path = [.a2uiPreview]
            default:
                if args[i + 1].hasPrefix("studio-") { studio = StudioRoom(rawValue: String(args[i + 1].dropFirst(7))) }
            }
        }
        #endif
    }

    /// Pushes [destination] with the system's slide (going back keeps the native, interactive pop).
    func push(_ destination: Destination) {
        guard path.last != destination else { return }
        path.append(destination)
    }

    /// Opens the Studio (Home, Imagine, the agent's results); the app stays where it was.
    func enterStudio(_ room: StudioRoom = .image) {
        withAnimation(.smooth) { studio = room }
    }

    func leaveStudio() {
        withAnimation(.smooth) { studio = nil }
    }

    /// Shows [destination] alone on [tab]'s stack (a chat chosen in the chat list beside it), without the slide.
    func show(_ destination: Destination, in tab: Tab) {
        guard paths[tab] != [destination] else { return }
        var transaction = Transaction()
        transaction.disablesAnimations = true
        withTransaction(transaction) { paths[tab] = [destination] }
    }

    func back() {
        if !path.isEmpty { path.removeLast() }
    }

    /// Goes to [tab]'s first screen (a shortcut to it from elsewhere).
    func switchTo(_ tab: Tab) {
        paths[tab] = []
        self.tab = tab
    }

    /// Replaces [tab]'s stack and shows it (welcome screen shortcuts, links).
    func reset(_ tab: Tab, _ destinations: [Destination] = []) {
        paths[tab] = destinations
        self.tab = tab
    }

    /// The stack of [tab], for its NavigationStack.
    func pathBinding(_ tab: Tab) -> Binding<[Destination]> {
        Binding(get: { self.paths[tab] ?? [] }, set: { self.paths[tab] = $0 })
    }
}

/**
 Navigation host, adaptive: the system's tab view, a tab bar on iPhone and a sidebar on iPad and
 the Mac (`sidebarAdaptable`), each tab with its own stack that it keeps when another is chosen,
 and the system navigation bar (screens fill it through [AutobotTopBar]). On a wide window the
 Run tab puts the chat list beside its stack (a split view), and a chat chosen there opens in it.
 */
struct AutobotNavHost: View {
    @Environment(Navigator.self) private var nav
    @Environment(\.horizontalSizeClass) private var sizeClass

    var body: some View {
        // The app stays underneath (its stack and screens keep their state) while the Studio is open.
        let inStudio = nav.studio != nil
        ZStack {
            app
                // Hidden, not removed: its stacks keep their state.
                .opacity(inStudio ? 0 : 1)
                .allowsHitTesting(!inStudio)
                .accessibilityHidden(inStudio)
            if inStudio {
                StudioScreen()
                    .transition(.opacity)
            }
        }
    }

    private var app: some View {
        @Bindable var nav = nav
        return TabView(selection: $nav.tab) {
            ForEach(Tab.allCases, id: \.self) { tab in
                SwiftUI.Tab(tab.title, systemImage: tab.symbol, value: tab) {
                    if tab == .run && sizeClass == .regular {
                        // A wide window: the chats beside Run's own stack, where the chat opens.
                        NavigationSplitView {
                            ChatListScreen(sidebar: true)
                                .navigationSplitViewColumnWidth(min: 300, ideal: 340, max: 420)
                        } detail: {
                            stack(tab)
                        }
                        .navigationSplitViewStyle(.balanced)
                    } else {
                        stack(tab)
                    }
                }
            }
        }
        .tabViewStyle(.sidebarAdaptable)
        .tint(Color.brandPurple)
    }

    /// [tab]'s own stack.
    private func stack(_ tab: Tab) -> some View {
        NavigationStack(path: nav.pathBinding(tab)) {
            root(tab)
                .navigationDestination(for: Destination.self) { destination in
                    screen(destination)
                        .background(Color(.systemBackground).ignoresSafeArea())
                }
        }
    }

    @ViewBuilder private func root(_ tab: Tab) -> some View {
        switch tab {
        case .run: RunScreen()
        case .models: ModelsScreen()
        case .remote: RemoteScreen()
        case .harness: HarnessScreen()
        case .settings: SettingsScreen()
        }
    }

    @ViewBuilder private func screen(_ destination: Destination) -> some View {
        switch destination {
        case .chatList: ChatListScreen()
        case .chat(let id): ChatScreen(conversationId: id).id(id)
        case .imagine(let handoff, let intent, let modelId, let prompt): ImagineScreen(handoffId: handoff, intent: intent, modelId: modelId, prompt: prompt)
        case .gallery(let openId): GalleryScreen(openId: openId)
        case .providers: ProvidersScreen()
        case .mcpServers: McpServersScreen()
        case .privacyCenter: PrivacyCenterScreen()
        case .imageBackends: BackendsScreen()
        case .accounts: AccountsScreen()
        case .compute: ComputeScreen()
        case .licenses: LicensesScreen()
        case .about: AboutScreen()
        case .memory: MemoryScreen()
        case .vault: VaultScreen()
        case .usage: UsageScreen()
        case .recipes: RecipesScreen()
        case .nodeAgent(let providerId, let open, let session, let bot):
            NodeAgentScreen(providerId: providerId, open: open, session: session, bot: bot).id("\(providerId)/\(session ?? "")/\(bot ?? "")")
        case .nodeBot(let providerId, let name): NodeBotScreen(providerId: providerId, name: name).id("\(providerId)/bot/\(name)")
        case .a2uiPreview: A2uiPreviewScreen()
        }
    }
}
